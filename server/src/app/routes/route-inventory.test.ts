import { createHash } from 'node:crypto'
import { expect, test } from 'bun:test'
import { createTestAppDependencies } from '../composition/api-dependencies'
import { createApp } from '../createApp'

test('preserves the complete HTTP method and canonical path inventory', () => {
  const application = createApp(createTestAppDependencies())
  const inventory = application.routes
    .map(({ method, path }) => `${method} ${path}`)
    .sort()

  expect(inventory).toHaveLength(495)
  expect(new Set(inventory).size).toBe(491)
  expect(inventory).toContain('PUT /api/teams/:teamId/issues/:issueId/parent')
  expect(inventory).toContain('GET /api/work-items/summary')
  expect(inventory).toContain('GET /api/workspace/calendar-settings')
  expect(inventory).not.toContain('GET /api/dashboard/summary')
  expect(inventory).toContain('GET /api/work-items/keys/:key')
  expect(inventory).toContain('GET /api/v1/work-items/:workItemId/key')
  expect(inventory).toContain('GET /api/teams/:teamId/work-item-hierarchy')
  expect(inventory).toContain('GET /api/teams/:teamId/projects/:projectId/raid-log')
  expect(inventory).toContain('POST /api/teams/:teamId/projects/:projectId/raid-log/entries')
  expect(inventory).toContain('PUT /api/teams/:teamId/projects/:projectId/raid-log/entries/:entryId')
  // A Work Item may be named `hierarchy`, so the Team hierarchy must not sit under `/issues/`.
  expect(inventory).not.toContain('GET /api/teams/:teamId/issues/hierarchy')
  expect(inventory).toContain('GET /api/teams/:teamId/issues/:issueId/children/open-count')
  expect(inventory).toContain('GET /api/v1/work-items/:workItemId/hierarchy')
  expect(inventory).toContain('POST /api/auth/refresh')
  expect(inventory).toContain('POST /api/auth/logout')
  expect(inventory).toContain('POST /api/auth/password-reset/request')
  expect(inventory).toContain('POST /api/auth/password-reset/confirm')
  expect(inventory).toContain('POST /api/auth/password/change')
  expect(inventory).toContain('GET /api/auth/account-security')
  expect(inventory).toContain('POST /api/auth/mfa/totp/associate')
  expect(inventory).toContain('POST /api/auth/mfa/totp/verify')
  expect(inventory).toContain('DELETE /api/auth/mfa/totp')
  expect(inventory).toContain('POST /api/auth/challenge/mfa-setup/associate')
  expect(inventory).toContain('POST /api/auth/challenge/mfa-setup/verify')
  expect(inventory).toContain('GET /api/workspace/members/sign-in-security')
  expect(inventory).toContain('POST /api/workspace/members/:memberKey/password-reset')
  expect(inventory).toContain('POST /api/workspace/members/:memberKey/mfa-reset')
  expect(inventory).toContain('GET /api/planning/update-feed')
  expect(inventory).toContain('GET /api/planning/archived-entities')
  expect(inventory).toContain('POST /api/planning/entities/:entityId/restore')
  expect(inventory).toContain('POST /api/planning/cycles/:cycleId/next')
  expect(inventory).toContain('POST /api/planning/cycles/:cycleId/work-items')
  expect(inventory).toContain('PUT /api/planning/update-feed/read-state')
  expect(inventory).toContain('GET /api/planning/update-feed/saved')
  expect(inventory).toContain('PUT /api/planning/update-feed/saved')
  expect(inventory).toContain('GET /api/planning/update-feed/options')
  expect(inventory).toContain('GET /api/planning/update-feed/digest')
  expect(inventory).toContain('PUT /api/planning/update-feed/digest')
  expect(inventory).toContain('POST /api/planning/update-feed/digest/preview')
  expect(inventory).toContain('GET /api/planning/update-feed/digest/inbox')
  expect(inventory).toContain('PUT /api/planning/update-feed/digest/inbox')
  expect(inventory).toContain('GET /api/v1/work-items/:workItemId/comments')
  expect(inventory).toContain('POST /api/audit/exports')
  expect(inventory).toContain('GET /api/audit/exports/:exportId/download')
  expect(inventory).toContain('POST /api/v1/work-items/:workItemId/comments')
  expect(inventory).toContain('GET /api/collections/candidates')
  expect(inventory).toContain('GET /api/collections/:collectionId/items')
  expect(inventory).toContain('PUT /api/collections/:collectionId/items/:teamId/:issueId')
  expect(inventory).toContain('GET /api/push/config')
  expect(inventory).toContain('PUT /api/push-subscriptions')
  expect(inventory).toContain('DELETE /api/push-subscriptions')
  expect(inventory).toContain('POST /api/v1/work-items/:workItemId/agent-runs')
  expect(inventory).toContain('GET /api/v1/work-items/:workItemId/agent-runs')
  expect(inventory).toContain('GET /api/v1/agent-runs')
  expect(inventory).toContain('GET /api/v1/agent-runs/:runId')
  expect(inventory).toContain('POST /api/v1/agent-runs/:runId/heartbeat')
  expect(inventory).toContain('POST /api/v1/agent-runs/:runId/finish')
  expect(inventory).toContain('POST /api/v1/agent-runs/:runId/reports')
  expect(inventory).toContain('POST /api/v1/work-items/:workItemId/agent-runs/:runId/take-over')
  expect(inventory).toContain('POST /api/v1/work-items/:workItemId/agent-runs/resume')
  expect(inventory).toContain('GET /api/v1/agent-settings')
  expect(inventory).toContain('GET /api/v1/agent-context')
  expect(inventory).toContain('GET /api/v1/work-items/:workItemId/acceptance-criteria')
  expect(inventory).toContain('GET /api/v1/work-items/:workItemId/effort')
  expect(inventory).toContain('GET /api/v1/work-items/:workItemId/actual-dates')
  expect(inventory).toContain('GET /api/teams/:teamId/work-items/:workItemId/agent-runs')
  expect(inventory).toContain('GET /api/teams/:teamId/work-items/:workItemId/agent-run-reports')
  expect(inventory).toContain('GET /api/teams/:teamId/agent-runs')
  expect(inventory).toContain('POST /api/teams/:teamId/agent-runs/:runId/release')
  expect(inventory).toContain('GET /api/teams/:teamId/agent-settings')
  expect(inventory).toContain('PUT /api/teams/:teamId/agent-settings')
  expect(inventory).toContain('GET /api/developer/me/agent-connection')
  expect(inventory).toContain('POST /api/developer/me/api-keys')
  expect(inventory).toContain('POST /api/developer/me/api-keys/:apiKeyId/rotate')
  expect(inventory).toContain('DELETE /api/developer/me/api-keys/:apiKeyId')
  expect(inventory).toContain('GET /api/me/preferences')
  expect(inventory).toContain('PUT /api/me/preferences')
  expect(inventory).toContain('GET /api/developer/credential-policy')
  expect(inventory).toContain('PUT /api/developer/credential-policy')
  // Team and Project IDs never change, so renaming is a PATCH on the stable resource.
  expect(inventory).toContain('GET /api/teams/directory')
  expect(inventory).toContain('PUT /api/teams/order')
  expect(inventory).toContain('PATCH /api/teams/:teamId')
  expect(inventory).toContain('PATCH /api/teams/:teamId/restore')
  expect(inventory).toContain('PUT /api/teams/:teamId/project-order')
  expect(inventory).toContain('PATCH /api/teams/:teamId/projects/:projectId')
  expect(inventory).toContain('PATCH /api/teams/:teamId/projects/:projectId/restore')
  // The Work Item estimate lives on the Work Item schedule, so time tracking has no estimate routes.
  expect(inventory.some((route) => route.endsWith('/time-estimate'))).toBe(false)
  expect(inventory.filter((route) => route === 'ALL /api/*')).toHaveLength(5)
  expect(createHash('sha256').update(inventory.join('\n')).digest('hex')).toBe(
    'e85921bf29f46c0b5c6a0dfe6a0bfc90bb71e3b6c19115dae70aaf924aa3fd8c',
  )
})
